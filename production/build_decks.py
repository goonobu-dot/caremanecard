def finalize(cards, subject, prefix):
    out = []
    seen_questions = set()
    for i, c in enumerate(cards, start=1):
        cid = f"{prefix}{i:03d}"
        if c["question"] in seen_questions:
            raise SystemExit(f"重複する質問文があります: {cid} {c['question']}")
        seen_questions.add(c["question"])
        full = {"id": cid, "subject": subject}
        full.update(c)
        out.append(full)
    return out


def write_deck(filename, subject, prefix, cards):
    finalized = finalize(cards, subject, prefix)
    payload = {"subject": subject, "cards": finalized}
    path = os.path.join(DECK_DIR, filename)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"wrote {path}: {len(finalized)} cards")


